create table public.orders (
  id uuid primary key default gen_random_uuid(),
  number text not null unique,
  mode text not null check (mode in ('diy','biz')),
  customer jsonb not null,
  ship_method text not null check (ship_method in ('std','exp','pickup')),
  payment_method text not null check (payment_method in ('card','transfer','invoice')),
  subtotal numeric(12,2) not null,
  shipping numeric(12,2) not null,
  vat numeric(12,2) not null,
  total numeric(12,2) not null,
  status text not null default 'received',
  created_at timestamptz not null default now()
);

create table public.order_lines (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id int not null references public.products(id),
  sku text not null,
  name text not null,
  qty int not null check (qty > 0),
  unit_price numeric(10,2) not null,
  line_total numeric(12,2) not null
);
create index order_lines_order_idx on public.order_lines (order_id);
create index order_lines_product_idx on public.order_lines (product_id);

