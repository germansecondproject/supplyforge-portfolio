-- SupplyForge storefront schema. Run once (Supabase SQL editor or `supabase db push`), then run supabase/seed.sql.
-- All product, stock and sales data is synthetic.

/* ---------- helpers ---------- */

-- EAN-13 checksum: weights 1,3,1,3... over the first 12 digits; the 13th digit makes the sum a multiple of 10.
create or replace function public.ean13_valid(code text) returns boolean
language sql immutable
set search_path = ''
as $$
  select code ~ '^[0-9]{13}$' and (
    (select sum(substr(code, i, 1)::int * case when i % 2 = 0 then 3 else 1 end) from generate_series(1, 12) i)
    + substr(code, 13, 1)::int
  ) % 10 = 0
$$;

create or replace function public.touch_updated_at() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

/* ---------- taxonomy ---------- */

create table public.categories (
  slug text primary key,
  name text not null,
  tone text not null,
  icon text not null,
  blurb text not null,
  position int not null
);

create table public.subcategories (
  category text not null references public.categories(slug) on delete cascade,
  slug text not null,
  name text not null,
  position int not null,
  primary key (category, slug)
);

create table public.brands (
  slug text primary key,
  name text not null,
  country char(2) not null
);

-- A family groups the sizes and versions of one product line ("Hex bolt DIN 933", "Measuring tape").
-- The product page uses it for the size configurator and the "other sizes" rail.
create table public.product_families (
  slug text primary key,
  name text not null,
  category text not null,
  subcategory text not null,
  variant_axes text[] not null default '{}', -- product attributes that differ inside the family: material, diameter_mm, length_mm, size...
  description text,
  foreign key (category, subcategory) references public.subcategories(category, slug)
);

/* ---------- products ---------- */

create table public.products (
  id int generated by default as identity primary key,
  item_code int not null unique check (item_code between 100000 and 999999),
  sku text not null unique,
  ean char(13) not null unique check (public.ean13_valid(ean)),
  slug text not null unique,
  name text not null,
  description text not null,
  highlights jsonb not null default '[]',   -- bullet points under the title
  key_specs jsonb not null default '[]',    -- three short facts for cards
  specifications jsonb not null default '[]', -- [[label, value], ...] for the specifications tab
  category text not null references public.categories(slug),
  subcategory text not null,
  brand text not null references public.brands(slug),
  family text not null references public.product_families(slug),
  -- variant attributes (null when they do not apply)
  standard text,
  material text,
  diameter_mm numeric(6,2),
  length_mm int,
  size_label text, -- free variant label for non-fasteners: "5 m", "Size 9", "Yellow"
  -- measurements of one sale unit (box, pack or item) as shipped
  pack_length_mm int not null check (pack_length_mm > 0),
  pack_width_mm int not null check (pack_width_mm > 0),
  pack_height_mm int not null check (pack_height_mm > 0),
  weight_kg numeric(8,3) not null check (weight_kg > 0),
  -- media
  image_url text not null,
  image_alt text not null,
  art jsonb not null default '{}', -- parameters for the procedural technical drawing
  -- selling
  pack_qty int not null default 1 check (pack_qty > 0),
  sale_unit text not null default 'each',
  volume_pricing boolean not null default false,
  min_order_qty int not null default 1 check (min_order_qty > 0),
  price_ex_vat numeric(10,2) not null check (price_ex_vat >= 0),
  vat_rate numeric(4,3) not null default 0.21 check (vat_rate >= 0 and vat_rate < 1),
  discount_pct numeric(5,2) not null default 0 check (discount_pct >= 0 and discount_pct < 100),
  price_inc_vat numeric(10,2) generated always as (round(price_ex_vat * (1 + vat_rate), 2)) stored,
  sale_price_ex_vat numeric(10,2) generated always as (round(price_ex_vat * (1 - discount_pct / 100), 2)) stored,
  sale_price_inc_vat numeric(10,2) generated always as (round(round(price_ex_vat * (1 - discount_pct / 100), 2) * (1 + vat_rate), 2)) stored,
  unavailable boolean not null default false, -- hides the buy button whatever the stock
  promo_enabled boolean not null default false,
  promo_text text,
  rating numeric(2,1) not null default 0 check (rating between 0 and 5),
  review_count int not null default 0 check (review_count >= 0),
  tags text[] not null default '{}',
  origin_country char(2) not null default 'ES',
  hs_code text, -- customs tariff code
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (category, subcategory) references public.subcategories(category, slug),
  check (not promo_enabled or coalesce(promo_text, '') <> '')
);
create index products_category_idx on public.products (category, subcategory);
create index products_family_idx on public.products (family);
create index products_brand_idx on public.products (brand);
create trigger products_touch before update on public.products for each row execute function public.touch_updated_at();

create table public.product_recommendations (
  product_id int not null references public.products(id) on delete cascade,
  recommended_id int not null references public.products(id) on delete cascade,
  kind text not null check (kind in ('accessory', 'bought_together', 'alternative')),
  position smallint not null default 1,
  primary key (product_id, recommended_id),
  check (product_id <> recommended_id)
);
create index product_recommendations_rec_idx on public.product_recommendations (recommended_id);

/* ---------- warehouses and stock ---------- */

create table public.warehouses (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  city text not null,
  country char(2) not null default 'ES',
  cutoff_time time not null default '14:00' -- orders before this time leave the same day
);

create table public.stock (
  product_id int not null references public.products(id) on delete cascade,
  warehouse_id smallint not null references public.warehouses(id) on delete cascade,
  location text not null check (location ~ '^[A-Z]-[0-9]{2}-[0-9]{2}-[A-Z]$'), -- aisle-rack-level-bin
  quantity int not null default 0 check (quantity >= 0),
  reserved int not null default 0 check (reserved >= 0 and reserved <= quantity),
  reorder_point int not null default 0 check (reorder_point >= 0),
  shipping_days smallint not null check (shipping_days between 0 and 30), -- working days from this warehouse to the customer
  restock_date date, -- next expected delivery when stock is low or out
  updated_at timestamptz not null default now(),
  primary key (product_id, warehouse_id)
);
create index stock_warehouse_idx on public.stock (warehouse_id);
create trigger stock_touch before update on public.stock for each row execute function public.touch_updated_at();

-- Per product: units that can be sold now, fastest delivery among warehouses that have them, next restock.
create view public.product_availability with (security_invoker = on) as
select
  s.product_id,
  sum(s.quantity - s.reserved)::int as available,
  min(s.shipping_days) filter (where s.quantity > s.reserved) as shipping_days,
  (array_agg(w.name order by s.shipping_days) filter (where s.quantity > s.reserved))[1] as ships_from,
  min(s.restock_date) as restock_date,
  count(*)::int as warehouses
from public.stock s
join public.warehouses w on w.id = s.warehouse_id
group by s.product_id;

/* ---------- sales ---------- */

-- Daily totals per product and channel. Seeded with a synthetic year; place_order() adds web/b2b orders.
create table public.sales (
  id bigint generated by default as identity primary key,
  product_id int not null references public.products(id) on delete cascade,
  sale_date date not null,
  channel text not null check (channel in ('web', 'b2b', 'marketplace')),
  units_sold int not null default 0 check (units_sold >= 0),
  units_returned int not null default 0 check (units_returned >= 0),
  revenue_ex_vat numeric(12,2) not null default 0,
  refunds_ex_vat numeric(12,2) not null default 0,
  unique (product_id, sale_date, channel)
);
create index sales_date_idx on public.sales (sale_date);

create view public.sales_monthly with (security_invoker = on) as
select
  date_trunc('month', sale_date)::date as month,
  product_id,
  sum(units_sold)::int as units_sold,
  sum(units_returned)::int as units_returned,
  sum(revenue_ex_vat) as revenue_ex_vat,
  sum(refunds_ex_vat) as refunds_ex_vat,
  sum(revenue_ex_vat - refunds_ex_vat) as net_revenue_ex_vat
from public.sales
group by 1, 2;

