import { cacheLife, cacheTag } from 'next/cache';
import { createClient } from '@supabase/supabase-js';
import local from '../../data/catalog.json';
import { toProduct } from './rows';
import type { ProductRow, StockRow } from './rows';
import type { Brand, Catalog, Category, Family, Recommendation, Subcategory } from './types';

export const supabaseConfigured = () => Boolean(process.env.NEXT_PUBLIC_SUPABASE_URL && process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY);

export function supabaseClient() {
  return createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
}

/**
 * The whole catalogue (~190 products) in one cached read. When Supabase env vars are set it comes from Postgres,
 * otherwise from data/catalog.json, which is generated by the same script as supabase/seed.sql.
 */
export async function getCatalog(): Promise<Catalog> {
  'use cache';
  cacheLife('hours');
  cacheTag('catalog');

  if (supabaseConfigured()) {
    try {
      const sb = supabaseClient();
      const [c, s, b, f, p, r, st] = await Promise.all([
        sb.from('categories').select('*').order('position'),
        sb.from('subcategories').select('*').order('position'),
        sb.from('brands').select('*').order('name'),
        sb.from('product_families').select('*'),
        sb.from('products').select('*').order('id').limit(1000),
        sb.from('product_recommendations').select('*').limit(5000),
        sb.from('stock').select('product_id,quantity,reserved,shipping_days,restock_date,warehouses(name,city)').limit(5000),
      ]);
      const err = [c, s, b, f, p, r, st].find((x) => x.error)?.error;
      if (err) throw new Error(err.message);
      if (p.data && p.data.length) {
        const byProduct = new Map<number, StockRow[]>();
        for (const row of (st.data ?? []) as unknown as StockRow[]) byProduct.set(row.product_id, [...(byProduct.get(row.product_id) ?? []), row]);
        return {
          categories: c.data as Category[],
          subcategories: s.data as Subcategory[],
          brands: b.data as Brand[],
          families: f.data as Family[],
          products: (p.data as ProductRow[]).map((x) => toProduct(x, byProduct.get(x.id) ?? [])),
          recommendations: r.data as Recommendation[],
        };
      }
    } catch (e) {
      console.error('Supabase read failed, using the bundled catalogue:', e);
    }
  }
  return local as unknown as Catalog;
}
